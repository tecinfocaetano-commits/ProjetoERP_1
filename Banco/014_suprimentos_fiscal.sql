/* ============================================================
   ERP 2026 - 014 - Suprimentos, Fiscal, Financeiro (fase 1)
   ------------------------------------------------------------
   Cria as tabelas da fase 1 do redesenho (ver
   Documentacao/DESENHO_NOVAS_ABAS.md):

     PRODUTO_FISCAL   classificacao fiscal (NCM/CEST/CFOP/CST/aliq)
     MATERIAL         insumo comprado/consumido (comb. produto fiscal)
     COR              cores do produto de producao (obrigatoria)
     PRODUTO_FINANCEIRO  servico/outros (comb. produto fiscal)
     PEDIDO_COMPRA    pedido de compra de materiais (+ item)
     ESTOQUE_MATERIAL estoque dos materiais
     MOVIMENTO_MATERIAL movimentos de estoque de materiais
     MOVIMENTO_FINANCEIRO movimentacao financeira (separada do Caixa)

   Acrescenta (aditivo, sem quebrar o existente):
     PRODUTO.PRODUTO_FISCAL_ID
     FICHA_TECNICA.TIPO_BASE / ID_BASE  (base generica)
     CONSUMO_MATERIAL_ITEM.STATUS_PRODUCAO  (andamento por talao)

   Nota sobre PRODUTO: o Firebird nao suporta ALTER TABLE ... RENAME.
   A tabela PRODUTO e mantida (ela ja e o produto de producao usado em
   pedido/venda); PRODUTO_PRODUCAO e o nome conceitual do modelo.

   Convencao do banco (igual ao 012): SEM chaves estrangeiras;
   integridade garantida pelo Service. Idempotente onde possivel.

   Aplicar com:
     isql -u SYSDBA -p masterkey Banco\DADOS.FDB -i Banco\014_suprimentos_fiscal.sql
   Reverter com:
     Banco\014_suprimentos_fiscal_rollback.sql
   ============================================================ */

SET ECHO ON;

/* ------------------------------------------------------------
   0) Protecao idempotente: ignora se ja existe
   ------------------------------------------------------------ */
/* Firebird nao tem IF NOT EXISTS para tabela; usamos excecao silenciosa
   via rdb$relations nas consultas de criacao. Para manter o script
   simples e de uso unico (como o 012), assumimos execucao unica. */

/* ------------------------------------------------------------
   1) GENERATORS
   ------------------------------------------------------------ */
CREATE GENERATOR GEN_PRODUTO_FISCAL_ID;
CREATE GENERATOR GEN_MATERIAL_ID;
CREATE GENERATOR GEN_COR_ID;
CREATE GENERATOR GEN_PRODUTO_FINANCEIRO_ID;
CREATE GENERATOR GEN_PEDIDO_COMPRA_ID;
CREATE GENERATOR GEN_PEDIDO_COMPRA_ITEM_ID;
CREATE GENERATOR GEN_ESTOQUE_MATERIAL_ID;
CREATE GENERATOR GEN_MOVIMENTO_MATERIAL_ID;
CREATE GENERATOR GEN_MOVIMENTO_FINANCEIRO_ID;

COMMIT;

/* ------------------------------------------------------------
   2) PRODUTO_FISCAL (classificacao fiscal reaproveitada)
   ------------------------------------------------------------ */
CREATE TABLE PRODUTO_FISCAL (
  ID                BIGINT NOT NULL PRIMARY KEY,
  EMPRESA_ID        BIGINT NOT NULL,
  CODIGO            VARCHAR(30),
  DESCRICAO         VARCHAR(100) NOT NULL,
  NCM               VARCHAR(10),
  CEST              VARCHAR(10),
  CFOP              VARCHAR(4),
  CFOP_VENDA        VARCHAR(5),
  CFOP_COMPRA       VARCHAR(5),
  CST_ICMS          VARCHAR(5),
  CST_PIS           VARCHAR(5),
  CST_COFINS        VARCHAR(5),
  ALIQ_ICMS         NUMERIC(15,4) DEFAULT 0,
  ALIQ_PIS          NUMERIC(15,4) DEFAULT 0,
  ALIQ_COFINS       NUMERIC(15,4) DEFAULT 0,
  PESO_LIQUIDO      NUMERIC(15,4) DEFAULT 0,
  PESO_BRUTO        NUMERIC(15,4) DEFAULT 0,
  ATIVO             CHAR(1) DEFAULT 'A',
  OBSERVACOES       VARCHAR(500),
  DATA_CADASTRO     TIMESTAMP,
  DATA_ATUALIZACAO  TIMESTAMP,
  CONSTRAINT CKB_PFISCAL_ATIVO CHECK (ATIVO IN ('A', 'I'))
);

/* ------------------------------------------------------------
   3) MATERIAL (insumo)
   ------------------------------------------------------------ */
CREATE TABLE MATERIAL (
  ID                  BIGINT NOT NULL PRIMARY KEY,
  EMPRESA_ID          BIGINT NOT NULL,
  PRODUTO_FISCAL_ID   BIGINT,
  UNIDADE_ID          BIGINT,
  CODIGO              VARCHAR(30),
  CODIGO_BARRAS       VARCHAR(20),
  DESCRICAO           VARCHAR(100) NOT NULL,
  PRECO_CUSTO         NUMERIC(15,4) DEFAULT 0,
  CONTROLA_ESTOQUE    CHAR(1) DEFAULT 'S',
  ESTOQUE_MINIMO      NUMERIC(15,4) DEFAULT 0,
  ATIVO               CHAR(1) DEFAULT 'A',
  OBSERVACOES         VARCHAR(500),
  DATA_CADASTRO       TIMESTAMP,
  DATA_ATUALIZACAO    TIMESTAMP,
  CONSTRAINT CKB_MAT_ATIVO CHECK (ATIVO IN ('A', 'I')),
  CONSTRAINT CKB_MAT_CTRL CHECK (CONTROLA_ESTOQUE IN ('S', 'N'))
);

/* ------------------------------------------------------------
   4) COR (cores do produto de producao - obrigatoria)
   ------------------------------------------------------------ */
CREATE TABLE COR (
  ID                  BIGINT NOT NULL PRIMARY KEY,
  EMPRESA_ID          BIGINT NOT NULL,
  PRODUTO_ID          BIGINT NOT NULL,   /* produto de producao (PRODUTO) */
  NOME                VARCHAR(60) NOT NULL,
  HEX                 VARCHAR(7),
  ATIVO               CHAR(1) DEFAULT 'A',
  DATA_CADASTRO       TIMESTAMP,
  CONSTRAINT CKB_COR_ATIVO CHECK (ATIVO IN ('A', 'I'))
);

/* ------------------------------------------------------------
   5) PRODUTO_FINANCEIRO (servico / outros)
   ------------------------------------------------------------ */
CREATE TABLE PRODUTO_FINANCEIRO (
  ID                  BIGINT NOT NULL PRIMARY KEY,
  EMPRESA_ID          BIGINT NOT NULL,
  PRODUTO_FISCAL_ID   BIGINT,
  CODIGO              VARCHAR(30),
  DESCRICAO           VARCHAR(100) NOT NULL,
  TIPO                CHAR(1) DEFAULT 'S',  /* S=servico, O=outros */
  VALOR               NUMERIC(15,4) DEFAULT 0,
  ATIVO               CHAR(1) DEFAULT 'A',
  OBSERVACOES         VARCHAR(500),
  DATA_CADASTRO       TIMESTAMP,
  DATA_ATUALIZACAO    TIMESTAMP,
  CONSTRAINT CKB_PRODFIN_TIPO CHECK (TIPO IN ('S', 'O')),
  CONSTRAINT CKB_PRODFIN_ATIVO CHECK (ATIVO IN ('A', 'I'))
);

/* ------------------------------------------------------------
   6) PEDIDO_COMPRA (+ item) - gera Nota de Entrada
   ------------------------------------------------------------ */
CREATE TABLE PEDIDO_COMPRA (
  ID                BIGINT NOT NULL PRIMARY KEY,
  EMPRESA_ID        BIGINT NOT NULL,
  FORNECEDOR_ID     BIGINT,
  NUMERO            VARCHAR(20),
  DATA_EMISSAO      DATE,
  DATA_ENTREGA      DATE,
  STATUS            VARCHAR(15) DEFAULT 'ABERTO',
  SUBTOTAL          NUMERIC(15,4) DEFAULT 0,
  DESCONTO          NUMERIC(15,4) DEFAULT 0,
  TOTAL             NUMERIC(15,4) DEFAULT 0,
  OBSERVACOES       VARCHAR(500),
  USUARIO_ID        BIGINT,
  NOTA_ENTRADA_ID   BIGINT,   /* nota gerada ao confirmar */
  DATA_CADASTRO     TIMESTAMP,
  DATA_ATUALIZACAO  TIMESTAMP,
  CONSTRAINT CKB_PCOMPRA_STATUS CHECK (STATUS IN ('ABERTO','CONFIRMADO','CANCELADO'))
);

CREATE TABLE PEDIDO_COMPRA_ITEM (
  ID                BIGINT NOT NULL PRIMARY KEY,
  PEDIDO_COMPRA_ID  BIGINT NOT NULL,
  MATERIAL_ID       BIGINT NOT NULL,
  QUANTIDADE        NUMERIC(15,4) DEFAULT 0,
  VALOR_UNITARIO    NUMERIC(15,4) DEFAULT 0,
  DESCONTO          NUMERIC(15,4) DEFAULT 0,
  VALOR_TOTAL       NUMERIC(15,4) DEFAULT 0,
  OBSERVACOES       VARCHAR(255),
  CONSTRAINT CKB_PCOMPRAITEM_QTD CHECK (QUANTIDADE > 0)
);

/* ------------------------------------------------------------
   7) ESTOQUE_MATERIAL e MOVIMENTO_MATERIAL
   ------------------------------------------------------------ */
CREATE TABLE ESTOQUE_MATERIAL (
  ID                BIGINT NOT NULL PRIMARY KEY,
  EMPRESA_ID        BIGINT NOT NULL,
  MATERIAL_ID       BIGINT NOT NULL,
  QUANTIDADE        NUMERIC(15,4) DEFAULT 0,
  DATA_ATUALIZACAO  TIMESTAMP,
  CONSTRAINT UQ_ESTQ_MAT UNIQUE (EMPRESA_ID, MATERIAL_ID)
);

CREATE TABLE MOVIMENTO_MATERIAL (
  ID                BIGINT NOT NULL PRIMARY KEY,
  EMPRESA_ID        BIGINT NOT NULL,
  MATERIAL_ID       BIGINT NOT NULL,
  TIPO              CHAR(1) NOT NULL,      /* E=entrada, S=saida */
  QUANTIDADE        NUMERIC(15,4) DEFAULT 0,
  SALDO_ANTERIOR    NUMERIC(15,4) DEFAULT 0,
  SALDO_POSTERIOR   NUMERIC(15,4) DEFAULT 0,
  CUSTO_UNITARIO    NUMERIC(15,4) DEFAULT 0,
  ORIGEM            VARCHAR(30),           /* COMPRA, CONSUMO, AJUSTE */
  DOCUMENTO_ID      BIGINT,                /* id do documento de origem */
  OBSERVACOES       VARCHAR(255),
  USUARIO_ID        BIGINT,
  DATA_MOVIMENTO    TIMESTAMP,
  CONSTRAINT CKB_MOVESTMAT_TIPO CHECK (TIPO IN ('E', 'S'))
);

/* ------------------------------------------------------------
   8) MOVIMENTO_FINANCEIRO (separada do Caixa)
   ------------------------------------------------------------ */
CREATE TABLE MOVIMENTO_FINANCEIRO (
  ID                BIGINT NOT NULL PRIMARY KEY,
  EMPRESA_ID        BIGINT NOT NULL,
  DATA_MOVIMENTO    DATE,
  TIPO              CHAR(1) NOT NULL,       /* E=entrada, S=saida */
  CATEGORIA         VARCHAR(30),            /* ex.: RECEBIMENTO, PAGAMENTO */
  DESCRICAO         VARCHAR(120),
  VALOR             NUMERIC(15,4) DEFAULT 0,
  CONTAPRODUCAO_ID  BIGINT,                 /* opcional: vinculo */
  DOCUMENTO_ID      BIGINT,
  USUARIO_ID        BIGINT,
  DATA_CADASTRO     TIMESTAMP,
  CONSTRAINT CKB_MOVFIN_TIPO CHECK (TIPO IN ('E', 'S'))
);

COMMIT;

/* ------------------------------------------------------------
