/* ============================================================
   ERP 2026 - Migracao 024
   Fiscal (marco 3.92) - nota de saida de servico resumida

   NOTA_SAIDA_SERVICO guarda uma nota de servico municipal emitida
   pelo ERP, sem estoque e sem contas a receber automaticas. Ela e
   a origem dos dados usados por TNFSeHelper para gerar o XML da
   DPS (Declaracao de Prestacao de Servicos) do padrao nacional.

   Regras:
     - isolamento por EMPRESA_ID da sessao;
     - SITUACAO: GERADA -> VALIDADA | ASSINADA | EMITIDA | CANCELADA
       | ERRO (EMITIDA so com NFSE_MODO=REAL e integracao homologada);
     - ID_DPS e CHAVE_NFSE unicidos por empresa para evitar duplicidade.
        O ID_DPS e gerado no INSERT (TNotaSaidaServicoService.Criar), porque
        o Firebird 5 trata NULL como repetido em indice UNIQUE;
     - identificadores <= 31 caracteres, DEFAULT antes de NOT NULL,
       sem ALTER ... RENAME (convencao do projeto).

   Execucao unica. Aplicar com:
     isql -u SYSDBA -p masterkey -charset UTF8 Banco\DADOS.FDB -i Banco\024_nota_saida_servico.sql
   Reverter com:
     Banco\024_nota_saida_servico_rollback.sql
   ============================================================ */

SET NAMES UTF8;
SET ECHO ON;

CREATE GENERATOR GEN_NOTA_SAIDA_SERVICO_ID;
COMMIT;

CREATE TABLE NOTA_SAIDA_SERVICO (
  ID                   BIGINT NOT NULL,
  EMPRESA_ID           BIGINT NOT NULL,
  PESSOA_ID            BIGINT,
  NUMERO               INTEGER NOT NULL,
  SERIE                VARCHAR(5) DEFAULT '1' NOT NULL,
  DATA_EMISSAO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  DATA_COMPETENCIA     DATE DEFAULT CURRENT_DATE NOT NULL,
  MUNICIPIO_IBGE       VARCHAR(7) NOT NULL,
  UF                   CHAR(2),
  INSCRICAO_MUNICIPAL  VARCHAR(15),
  CODIGO_SERVICO       VARCHAR(6) NOT NULL,
  DESCRICAO_SERVICO    VARCHAR(200) NOT NULL,
  VALOR_SERVICO        NUMERIC(15,2) DEFAULT 0 NOT NULL,
  DESCONTO             NUMERIC(15,2) DEFAULT 0 NOT NULL,
  ALIQUOTA_ISS         NUMERIC(5,2) DEFAULT 0 NOT NULL,
  VALOR_ISS            NUMERIC(15,2) DEFAULT 0 NOT NULL,
  TIPO_RETENCAO_ISS    CHAR(1) DEFAULT '1' NOT NULL
    CONSTRAINT CK_NSS_RETENCAO_ISS CHECK (TIPO_RETENCAO_ISS IN ('1','2','3')),
  VALOR_RET_PIS        NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_RET_COFINS     NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_RET_INSS       NUMERIC(15,2) DEFAULT 0 NOT NULL,
  PROVEDOR             VARCHAR(20) DEFAULT 'NACIONAL' NOT NULL,
  ID_DPS               VARCHAR(45),
  CHAVE_NFSE           VARCHAR(50),
  PROTOCOLO            VARCHAR(50),
  SITUACAO             VARCHAR(15) DEFAULT 'GERADA' NOT NULL
    CONSTRAINT CK_NSS_SITUACAO CHECK (SITUACAO IN
      ('GERADA','VALIDADA','ASSINADA','EMITIDA','CANCELADA','ERRO')),
  XML_ARQUIVO          VARCHAR(255),
  OBSERVACAO           VARCHAR(500),
  USUARIO_ID           BIGINT,
  DATA_CRIACAO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PRIMARY KEY (ID)
);
COMMIT;

CREATE UNIQUE INDEX UQ_NSS_EMP_SERIE_NUM
  ON NOTA_SAIDA_SERVICO (EMPRESA_ID, SERIE, NUMERO);
CREATE UNIQUE INDEX UQ_NSS_EMP_ID_DPS
  ON NOTA_SAIDA_SERVICO (EMPRESA_ID, ID_DPS);
CREATE INDEX IX_NSS_PESSOA ON NOTA_SAIDA_SERVICO (PESSOA_ID);
CREATE INDEX IX_NSS_CHAVE ON NOTA_SAIDA_SERVICO (CHAVE_NFSE);
COMMIT;

SET TERM ^ ;

CREATE TRIGGER TRG_NOTA_SAIDA_SERVICO_BI
  FOR NOTA_SAIDA_SERVICO ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ID IS NULL OR NEW.ID = 0) THEN
    NEW.ID = GEN_ID(GEN_NOTA_SAIDA_SERVICO_ID, 1);
  IF (NEW.SERIE IS NULL OR NEW.SERIE = '') THEN
    NEW.SERIE = '1';
  IF (NEW.PROVEDOR IS NULL OR NEW.PROVEDOR = '') THEN
    NEW.PROVEDOR = 'NACIONAL';
  IF (NEW.SITUACAO IS NULL OR NEW.SITUACAO = '') THEN
    NEW.SITUACAO = 'GERADA';
  IF (NEW.DATA_EMISSAO IS NULL) THEN
    NEW.DATA_EMISSAO = CURRENT_TIMESTAMP;
  IF (NEW.DATA_COMPETENCIA IS NULL) THEN
    NEW.DATA_COMPETENCIA = CURRENT_DATE;
  IF (NEW.DATA_CRIACAO IS NULL) THEN
    NEW.DATA_CRIACAO = CURRENT_TIMESTAMP;
END
^

SET TERM ; ^
COMMIT;

