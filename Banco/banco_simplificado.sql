-- 4. Criar tabelas principais
CREATE TABLE EMPRESA (
  ID              DM_ID PRIMARY KEY,
  RAZAO_SOCIAL    DM_NOME,
  NOME_FANTASIA   DM_NOME,
  CNPJ            VARCHAR(18),
  IE              VARCHAR(20),
  ENDERECO        VARCHAR(200),
  CIDADE          VARCHAR(100),
  UF              CHAR(2),
  CEP             VARCHAR(10),
  TELEFONE        VARCHAR(20),
  EMAIL           VARCHAR(150),
  ATIVO           DM_STATUS
);

CREATE TABLE GRUPO (
  ID              DM_ID PRIMARY KEY,
  NOME            DM_NOME,
  DESCRICAO       DM_DESCRICAO,
  ATIVO           DM_STATUS
);

CREATE TABLE USUARIO (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  GRUPO_ID        DM_ID,
  NOME            DM_NOME,
  LOGIN           VARCHAR(50),
  SENHA           VARCHAR(100),
  EMAIL           VARCHAR(150),
  ADMINISTRADOR    CHAR(1) DEFAULT 'N',
  ATIVO           DM_STATUS,
  ULTIMO_ACESSO   DM_DATA
);

CREATE TABLE CLIENTE (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  NOME            DM_NOME,
  NOME_FANTASIA   VARCHAR(100),
  CPF_CNPJ        VARCHAR(18),
  RG_IE           VARCHAR(20),
  ENDERECO        VARCHAR(200),
  NUMERO          VARCHAR(20),
  COMPLEMENTO     VARCHAR(100),
  BAIRRO          VARCHAR(100),
  CIDADE          VARCHAR(100),
  UF              CHAR(2),
  CEP             VARCHAR(10),
  TELEFONE        VARCHAR(20),
  EMAIL           VARCHAR(150),
  ATIVO           DM_STATUS
);

CREATE TABLE FORNECEDOR (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  RAZAO_SOCIAL    DM_NOME,
  NOME_FANTASIA   DM_NOME,
  CNPJ            VARCHAR(18),
  IE              VARCHAR(20),
  ENDERECO        VARCHAR(200),
  CIDADE          VARCHAR(100),
  UF              CHAR(2),
  CEP             VARCHAR(10),
  TELEFONE        VARCHAR(20),
  EMAIL           VARCHAR(150),
  CONTATO         VARCHAR(100),
  ATIVO           DM_STATUS
);

CREATE TABLE CATEGORIA (
  ID              DM_ID PRIMARY KEY,
  NOME            DM_NOME,
  DESCRICAO       DM_DESCRICAO,
  ATIVO           DM_STATUS
);

CREATE TABLE UNIDADE (
  ID              DM_ID PRIMARY KEY,
  NOME            DM_NOME,
  ABREVIATURA     VARCHAR(10),
  ATIVO           DM_STATUS
);

CREATE TABLE PRODUTO (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  CATEGORIA_ID    DM_ID,
  UNIDADE_ID      DM_ID,
  CODIGO          VARCHAR(30),
  CODIGO_BARRAS   VARCHAR(20),
  DESCRICAO       DM_NOME,
  PRECO_CUSTO      DM_VALOR,
  PRECO_VENDA     DM_VALOR,
  MARGEM_LUCRO    DM_VALOR,
  ESTOQUE_MINIMO   DM_VALOR,
  ESTOQUE_MAXIMO   DM_VALOR,
  CONTROLA_ESTOQUE CHAR(1) DEFAULT 'N',
  NCM             VARCHAR(10),
  CEST            VARCHAR(10),
  CFOP            VARCHAR(4),
  ATIVO           DM_STATUS
);

CREATE TABLE ESTOQUE (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  PRODUTO_ID      DM_ID,
  QUANTIDADE      DM_VALOR,
  QUANTIDADE_MINIMA DM_VALOR,
  QUANTIDADE_MAXIMA DM_VALOR,
  LOCALIZACAO     VARCHAR(100)
);

CREATE TABLE MOVIMENTO_ESTOQUE (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  PRODUTO_ID      DM_ID,
  TIPO            CHAR(1),
  QUANTIDADE      DM_VALOR,
  CUSTO_UNITARIO   DM_VALOR,
  DOCUMENTO       VARCHAR(50),
  OBSERVACAO      DM_DESCRICAO,
  DATA_MOVIMENTO   DM_DATA,
  USUARIO_ID      DM_ID
);

CREATE TABLE PEDIDO_VENDA (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  CLIENTE_ID      DM_ID,
  NUMERO          VARCHAR(20),
  DATA_EMISSAO     DM_DATA,
  DATA_ENTREGA     DM_DATA,
  STATUS          CHAR(1) DEFAULT 'A',
  SUBTOTAL        DM_VALOR,
  DESCONTO        DM_VALOR,
  TOTAL           DM_VALOR,
  OBSERVACOES     DM_DESCRICAO
);

CREATE TABLE ITEM_PEDIDO (
  ID              DM_ID PRIMARY KEY,
  PEDIDO_VENDA_ID DM_ID,
  PRODUTO_ID      DM_ID,
  QUANTIDADE      DM_VALOR,
  PRECO_UNITARIO  DM_VALOR,
  VALOR_TOTAL     DM_VALOR,
  DESCONTO        DM_VALOR
);

CREATE TABLE FINANCEIRO (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  TIPO            CHAR(1),
  DESCRICAO       DM_DESCRICAO,
  VALOR           DM_VALOR,
  DATA_VENCIMENTO  DM_DATA,
  STATUS          CHAR(1)
);

CREATE TABLE CONTA_RECEBER (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  FINANCEIRO_ID    DM_ID,
  CLIENTE_ID      DM_ID,
  DESCRICAO       DM_DESCRICAO,
  VALOR           DM_VALOR,
  DATA_VENCIMENTO  DM_DATA,
  DATA_PAGAMENTO   DM_DATA,
  VALOR_PAGO      DM_VALOR,
  STATUS          CHAR(1)
);

CREATE TABLE CONTA_PAGAR (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  FINANCEIRO_ID    DM_ID,
  FORNECEDOR_ID   DM_ID,
  DESCRICAO       DM_DESCRICAO,
  VALOR           DM_VALOR,
  DATA_VENCIMENTO  DM_DATA,
  DATA_PAGAMENTO   DM_DATA,
  VALOR_PAGO      DM_VALOR,
  STATUS          CHAR(1)
);

CREATE TABLE CAIXA (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  USUARIO_ID      DM_ID,
  NUMERO          VARCHAR(20),
  DATA_ABERTURA   DM_DATA,
  VALOR_ABERTURA  DM_VALOR,
  STATUS          CHAR(1) DEFAULT 'A'
);

CREATE TABLE MOVIMENTO_CAIXA (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  CAIXA_ID        DM_ID,
  TIPO            CHAR(1),
  VALOR           DM_VALOR,
  DESCRICAO       DM_DESCRICAO,
  DATA_MOVIMENTO   DM_DATA,
  USUARIO_ID      DM_ID
);

CREATE TABLE LOG_SISTEMA (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  USUARIO_ID      DM_ID,
  TABELA          VARCHAR(50),
  OPERACAO        VARCHAR(20),
  REGISTRO_ID     DM_ID,
  DADOS_ANTERIORES DM_DESCRICAO,
  DADOS_NOVOS     DM_DESCRICAO,
  DATA_OPERACAO   DM_DATA
);

CREATE TABLE CONFIGURACAO (
  ID              DM_ID PRIMARY KEY,
  EMPRESA_ID      DM_ID,
  CHAVE           VARCHAR(50),
  VALOR           DM_DESCRICAO
);

