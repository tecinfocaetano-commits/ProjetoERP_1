BEGIN
  IF (NEW.TIPO = 'E' OR NEW.TIPO = 'A') THEN
    V_QTD = NEW.QUANTIDADE;
  ELSE IF (NEW.TIPO = 'S') THEN
    V_QTD = -NEW.QUANTIDADE;
  ELSE
    V_QTD = 0;

  UPDATE ESTOQUE
     SET QUANTIDADE = COALESCE(QUANTIDADE, 0) + :V_QTD,
         DATA_ATUALIZACAO = CURRENT_TIMESTAMP
   WHERE EMPRESA_ID = NEW.EMPRESA_ID AND PRODUTO_ID = NEW.PRODUTO_ID;

  IF (ROW_COUNT = 0) THEN
    INSERT INTO ESTOQUE (ID, EMPRESA_ID, PRODUTO_ID, QUANTIDADE, DATA_ATUALIZACAO)
    VALUES (GEN_ID(GEN_ESTOQUE_ID, 1), NEW.EMPRESA_ID, NEW.PRODUTO_ID, :V_QTD, CURRENT_TIMESTAMP);
END
