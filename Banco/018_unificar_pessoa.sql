/* ============================================================
   ERP 2026 - Migracao 018
   Unificacao de CLIENTE + FORNECEDOR em PESSOA (D3)

   Decisoes aprovadas:
     - tabela unica PESSOA com TIPO C (cliente) / F (fornecedor);
     - IDs de CLIENTE preservados;
     - IDs de FORNECEDOR remapeados acima do maior ID existente
       (tabela MIGRA_FORN_018 guarda o de-para para rollback);
     - colunas CLIENTE_ID / FORNECEDOR_ID NAO sao renomeadas:
       passam a referenciar PESSOA.ID;
     - sem FKs reais (padrao do banco), integridade nas Services.

   Execucao unica. Aplicar com:
     isql -u SYSDBA -p masterkey -charset UTF8 Banco\DADOS.FDB -i Banco\018_unificar_pessoa.sql
   Reverter com:
     Banco\018_unificar_pessoa_rollback.sql
   ============================================================ */

SET NAMES UTF8;
SET ECHO ON;

/* ------------------------------------------------------------
   1) Tabela unica + gerador
   ------------------------------------------------------------ */

CREATE GENERATOR GEN_PESSOA_ID;
COMMIT;

CREATE TABLE PESSOA (
  ID                DM_ID NOT NULL,
  EMPRESA_ID        DM_ID,
  TIPO              CHAR(1) DEFAULT 'C' NOT NULL,
  TIPO_PESSOA       CHAR(1) DEFAULT 'F',
  NOME              DM_NOME,
  NOME_FANTASIA     VARCHAR(100),
  CPF_CNPJ          VARCHAR(20),
  RG_IE             VARCHAR(20),
  ENDERECO          VARCHAR(200),
  NUMERO            VARCHAR(20),
  COMPLEMENTO       VARCHAR(100),
  BAIRRO            VARCHAR(100),
  CIDADE            VARCHAR(100),
  CIDADE_ID         BIGINT,
  UF                CHAR(2),
  CEP               VARCHAR(10),
  TELEFONE          VARCHAR(20),
  CELULAR           VARCHAR(20),
  EMAIL             VARCHAR(150),
  CONTATO           VARCHAR(100),
  DATA_NASCIMENTO   DATE,
  LIMITE_CREDITO    NUMERIC(15,4),
  OBSERVACOES       VARCHAR(1000),
  ATIVO             DM_STATUS,
  DATA_CADASTRO     TIMESTAMP,
  PRIMARY KEY (ID),
  CONSTRAINT CK_PESSOA_TIPO CHECK (TIPO IN ('C', 'F')),
  CONSTRAINT CK_PESSOA_ATIVO CHECK (ATIVO IS NULL OR ATIVO IN ('A', 'I'))
);
COMMIT;

SET TERM ^ ;
CREATE TRIGGER TRG_PESSOA_BI FOR PESSOA ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ID IS NULL OR NEW.ID = 0) THEN
    NEW.ID = GEN_ID(GEN_PESSOA_ID, 1);
  IF (NEW.DATA_CADASTRO IS NULL) THEN
    NEW.DATA_CADASTRO = CURRENT_TIMESTAMP;
END^
SET TERM ; ^
COMMIT;

/* ------------------------------------------------------------
   2) Copia dos CLIENTES (IDs preservados)
   ------------------------------------------------------------ */

INSERT INTO PESSOA (
  ID, EMPRESA_ID, TIPO, TIPO_PESSOA, NOME, NOME_FANTASIA,
  CPF_CNPJ, RG_IE, ENDERECO, NUMERO, COMPLEMENTO, BAIRRO,
  CIDADE, CIDADE_ID, UF, CEP, TELEFONE, CELULAR, EMAIL,
  DATA_NASCIMENTO, LIMITE_CREDITO, OBSERVACOES, ATIVO, DATA_CADASTRO
)
SELECT
  ID, EMPRESA_ID, 'C', TIPO_PESSOA, NOME, NOME_FANTASIA,
  CPF_CNPJ, RG_IE, ENDERECO, NUMERO, COMPLEMENTO, BAIRRO,
  CIDADE, CIDADE_ID, UF, CEP, TELEFONE, CELULAR, EMAIL,
  DATA_NASCIMENTO, LIMITE_CREDITO, OBSERVACOES, ATIVO, DATA_CADASTRO
FROM CLIENTE;
COMMIT;

/* ------------------------------------------------------------
   3) FORNECEDORES com IDs novos (acima de MAX(cliente, fornecedor))
   ------------------------------------------------------------ */

CREATE TABLE MIGRA_FORN_018 (
  ID_ANTIGO    BIGINT NOT NULL PRIMARY KEY,
  ID_NOVO      BIGINT NOT NULL UNIQUE,
  CNPJ_ANTIGO  VARCHAR(18)
);
COMMIT;

CREATE TABLE MIGRA_BASE_018 (
  BASE BIGINT
);
COMMIT;

INSERT INTO MIGRA_BASE_018 (BASE)
SELECT CASE
         WHEN (SELECT COALESCE(MAX(ID), 0) FROM CLIENTE) >
              (SELECT COALESCE(MAX(ID), 0) FROM FORNECEDOR)
         THEN (SELECT COALESCE(MAX(ID), 0) FROM CLIENTE)
         ELSE (SELECT COALESCE(MAX(ID), 0) FROM FORNECEDOR)
       END
FROM RDB$DATABASE;
COMMIT;

INSERT INTO MIGRA_FORN_018 (ID_ANTIGO, ID_NOVO, CNPJ_ANTIGO)
SELECT F.ID, B.BASE + ROW_NUMBER() OVER (ORDER BY F.ID), F.CNPJ
FROM FORNECEDOR F
CROSS JOIN MIGRA_BASE_018 B;
COMMIT;

INSERT INTO PESSOA (
  ID, EMPRESA_ID, TIPO, TIPO_PESSOA, NOME, NOME_FANTASIA,
  CPF_CNPJ, RG_IE, ENDERECO, NUMERO, COMPLEMENTO, BAIRRO,
  CIDADE, CIDADE_ID, UF, CEP, TELEFONE, CELULAR, EMAIL,
  CONTATO, OBSERVACOES, ATIVO, DATA_CADASTRO
)
SELECT
  M.ID_NOVO, F.EMPRESA_ID, 'F', F.TIPO_PESSOA, F.RAZAO_SOCIAL,
  F.NOME_FANTASIA, F.CPF_CNPJ, F.IE, F.ENDERECO, F.NUMERO,
  F.COMPLEMENTO, F.BAIRRO, F.CIDADE, F.CIDADE_ID, F.UF, F.CEP,
  F.TELEFONE, F.CELULAR, F.EMAIL, F.CONTATO, F.OBSERVACOES,
  F.ATIVO, F.DATA_CADASTRO
FROM FORNECEDOR F
JOIN MIGRA_FORN_018 M ON M.ID_ANTIGO = F.ID;
COMMIT;

/* ------------------------------------------------------------
   4) Remapeamento das referencias de FORNECEDOR
   ------------------------------------------------------------ */

UPDATE CONTA_PAGAR SET FORNECEDOR_ID =
  (SELECT M.ID_NOVO FROM MIGRA_FORN_018 M
    WHERE M.ID_ANTIGO = CONTA_PAGAR.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_018 M
               WHERE M.ID_ANTIGO = CONTA_PAGAR.FORNECEDOR_ID);

UPDATE NOTA_ENTRADA SET FORNECEDOR_ID =
  (SELECT M.ID_NOVO FROM MIGRA_FORN_018 M
    WHERE M.ID_ANTIGO = NOTA_ENTRADA.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_018 M
               WHERE M.ID_ANTIGO = NOTA_ENTRADA.FORNECEDOR_ID);

UPDATE PEDIDO_COMPRA SET FORNECEDOR_ID =
  (SELECT M.ID_NOVO FROM MIGRA_FORN_018 M
    WHERE M.ID_ANTIGO = PEDIDO_COMPRA.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_018 M
               WHERE M.ID_ANTIGO = PEDIDO_COMPRA.FORNECEDOR_ID);

UPDATE PRODUTO SET FORNECEDOR_ID =
  (SELECT M.ID_NOVO FROM MIGRA_FORN_018 M
    WHERE M.ID_ANTIGO = PRODUTO.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_018 M
               WHERE M.ID_ANTIGO = PRODUTO.FORNECEDOR_ID);

UPDATE FINANCEIRO SET FORNECEDOR_ID =
  (SELECT M.ID_NOVO FROM MIGRA_FORN_018 M
    WHERE M.ID_ANTIGO = FINANCEIRO.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_018 M
               WHERE M.ID_ANTIGO = FINANCEIRO.FORNECEDOR_ID);
COMMIT;

/* ------------------------------------------------------------
   5) Gerador unico avancado ate o maior ID gravado
   ------------------------------------------------------------ */

SET TERM ^ ;
EXECUTE BLOCK AS
  DECLARE VMAX BIGINT;
  DECLARE VNOW BIGINT;
BEGIN
  SELECT COALESCE(MAX(ID), 0) FROM PESSOA INTO :VMAX;
  VNOW = GEN_ID(GEN_PESSOA_ID, 0);
  WHILE (VNOW < VMAX) DO
    VNOW = GEN_ID(GEN_PESSOA_ID, 1);
END^
SET TERM ; ^
COMMIT;

/* ------------------------------------------------------------
   6) Remocao das estruturas antigas
   ------------------------------------------------------------ */

DROP TRIGGER TRG_CLIENTE_BI;
DROP TRIGGER TRG_FORNECEDOR_BI;
COMMIT;

DROP TABLE CLIENTE;
DROP TABLE FORNECEDOR;
COMMIT;

DROP GENERATOR GEN_CLIENTE_ID;
DROP GENERATOR GEN_FORNECEDOR_ID;
COMMIT;

DROP TABLE MIGRA_BASE_018;
COMMIT;

/* ------------------------------------------------------------
   7) Indices da PESSOA
   ------------------------------------------------------------ */

CREATE INDEX IDX_PESSOA_EMPRESA_TIPO ON PESSOA (EMPRESA_ID, TIPO, NOME);
CREATE INDEX IDX_PESSOA_CPF ON PESSOA (CPF_CNPJ);
CREATE INDEX IDX_PESSOA_CIDADE ON PESSOA (CIDADE_ID);
COMMIT;

/* ------------------------------------------------------------
   8) Validacoes (conferir a saida)
   ------------------------------------------------------------ */

SELECT TIPO, COUNT(*) AS QTD FROM PESSOA GROUP BY TIPO ORDER BY TIPO;

SELECT COUNT(*) AS MAPEAMENTO FROM MIGRA_FORN_018;

SELECT 'CONTA_RECEBER' AS TABELA, COUNT(*) AS ORFAOS
FROM CONTA_RECEBER CR
WHERE CR.CLIENTE_ID > 0
  AND NOT EXISTS (SELECT 1 FROM PESSOA P WHERE P.ID = CR.CLIENTE_ID AND P.TIPO = 'C')
UNION ALL
SELECT 'CONTA_PAGAR', COUNT(*)
FROM CONTA_PAGAR CP
WHERE CP.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM PESSOA P WHERE P.ID = CP.FORNECEDOR_ID AND P.TIPO = 'F')
UNION ALL
SELECT 'NOTA_ENTRADA', COUNT(*)
FROM NOTA_ENTRADA N
WHERE N.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM PESSOA P WHERE P.ID = N.FORNECEDOR_ID AND P.TIPO = 'F')
UNION ALL
SELECT 'NOTA_SAIDA', COUNT(*)
FROM NOTA_SAIDA N
WHERE N.CLIENTE_ID > 0
  AND NOT EXISTS (SELECT 1 FROM PESSOA P WHERE P.ID = N.CLIENTE_ID AND P.TIPO = 'C')
UNION ALL
SELECT 'PEDIDO_COMPRA', COUNT(*)
FROM PEDIDO_COMPRA PC
WHERE PC.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM PESSOA P WHERE P.ID = PC.FORNECEDOR_ID AND P.TIPO = 'F')
UNION ALL
SELECT 'PEDIDO_VENDA', COUNT(*)
FROM PEDIDO_VENDA PV
WHERE PV.CLIENTE_ID > 0
  AND NOT EXISTS (SELECT 1 FROM PESSOA P WHERE P.ID = PV.CLIENTE_ID AND P.TIPO = 'C')
UNION ALL
SELECT 'PRODUTO', COUNT(*)
FROM PRODUTO PR
WHERE PR.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM PESSOA P WHERE P.ID = PR.FORNECEDOR_ID AND P.TIPO = 'F')
UNION ALL
SELECT 'FINANCEIRO_CLI', COUNT(*)
FROM FINANCEIRO F
WHERE F.CLIENTE_ID > 0
  AND NOT EXISTS (SELECT 1 FROM PESSOA P WHERE P.ID = F.CLIENTE_ID AND P.TIPO = 'C')
UNION ALL
SELECT 'FINANCEIRO_FORN', COUNT(*)
FROM FINANCEIRO F
WHERE F.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM PESSOA P WHERE P.ID = F.FORNECEDOR_ID AND P.TIPO = 'F');

SELECT GEN_ID(GEN_PESSOA_ID, 0) AS GERADOR_ATUAL,
       (SELECT MAX(ID) FROM PESSOA) AS MAIOR_ID
FROM RDB$DATABASE;

SELECT COUNT(*) AS TABELAS_ANTIGAS
FROM RDB$RELATIONS
WHERE TRIM(RDB$RELATION_NAME) IN ('CLIENTE', 'FORNECEDOR');

