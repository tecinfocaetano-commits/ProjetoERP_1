SET LIST ON;

-- 1) Remove dados de teste criados durante a validacao da API
DELETE FROM MOVIMENTO_ESTOQUE WHERE DOCUMENTO IN ('TESTE-API','VENDA-API');
DELETE FROM PRODUTO WHERE CODIGO STARTING WITH 'TST-';
DELETE FROM CLIENTE WHERE CPF_CNPJ IN ('111.222.333-44','555.666.777-88');

-- 2) Sincroniza os generators com o maior ID de cada tabela.
--    Sem isso, novos registros recebem IDs baixos e podem colidir com os existentes.
SET TERM ^ ;
EXECUTE BLOCK AS
DECLARE v_n BIGINT;
BEGIN
  SELECT COALESCE(MAX(ID),0) FROM EMPRESA INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_EMPRESA_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM USUARIO INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_USUARIO_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM GRUPO INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_GRUPO_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM CLIENTE INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_CLIENTE_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM FORNECEDOR INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_FORNECEDOR_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM CATEGORIA INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_CATEGORIA_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM UNIDADE INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_UNIDADE_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM PRODUTO INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_PRODUTO_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM ESTOQUE INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_ESTOQUE_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM MOVIMENTO_ESTOQUE INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_MOVIMENTO_ESTOQUE_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM PEDIDO_VENDA INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_PEDIDO_VENDA_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM ITEM_PEDIDO INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_ITEM_PEDIDO_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM FINANCEIRO INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_FINANCEIRO_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM CONTA_RECEBER INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_CONTA_RECEBER_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM CONTA_PAGAR INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_CONTA_PAGAR_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM CAIXA INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_CAIXA_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM MOVIMENTO_CAIXA INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_MOVIMENTO_CAIXA_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM LOG_SISTEMA INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_LOG_SISTEMA_ID TO ' || :v_n;
  SELECT COALESCE(MAX(ID),0) FROM CONFIGURACAO INTO :v_n;
  EXECUTE STATEMENT 'SET GENERATOR GEN_CONFIGURACAO_ID TO ' || :v_n;
END^
SET TERM ; ^

COMMIT;

-- 3) Conferencia
