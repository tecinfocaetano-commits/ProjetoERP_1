/* ============================================================
   ERP 2026 - ROLLBACK da Migracao 018
   Reverte a unificacao de CLIENTE + FORNECEDOR em PESSOA.

   Ordem:
     1) recriar geradores/tabelas/triggers/indices antigos;
     2) copiar PESSOA.TIPO='C' para CLIENTE (IDs preservados);
     3) copiar PESSOA.TIPO='F' para FORNECEDOR (mapa inverso);
     4) reverter as 5 colunas FORNECEDOR_ID;
     5) avancar GEN_CLIENTE_ID / GEN_FORNECEDOR_ID;
     6) remover PESSOA e artefatos da 018.

   LIMITE: o rollback nao ressuscita registros apagados depois da 018.
   Para perda de dados, restaurar o backup DADOS_backup_antes_018.fdb.

   Aplicar com:
     isql -u SYSDBA -p masterkey -charset UTF8 Banco\DADOS.FDB -i Banco\018_unificar_pessoa_rollback.sql
   ============================================================ */

SET NAMES UTF8;
SET ECHO ON;

/* ------------------------------------------------------------
   1) Estruturas antigas (mesmo DDL do schema canonico)
   ------------------------------------------------------------ */

CREATE GENERATOR GEN_CLIENTE_ID;
CREATE GENERATOR GEN_FORNECEDOR_ID;
COMMIT;

CREATE TABLE CLIENTE (
  ID                DM_ID NOT NULL,
  EMPRESA_ID        DM_ID,
  NOME              DM_NOME,
  NOME_FANTASIA     VARCHAR(100),
  CPF_CNPJ          VARCHAR(18),
  RG_IE             VARCHAR(20),
  ENDERECO          VARCHAR(200),
  NUMERO            VARCHAR(20),
  COMPLEMENTO       VARCHAR(100),
  BAIRRO            VARCHAR(100),
  CIDADE            VARCHAR(100),
  UF                CHAR(2),
  CEP               VARCHAR(10),
  TELEFONE          VARCHAR(20),
  EMAIL             VARCHAR(150),
  ATIVO             DM_STATUS,
  TIPO_PESSOA       CHAR(1) DEFAULT 'F',
  CELULAR           VARCHAR(20),
  DATA_NASCIMENTO   DATE,
  LIMITE_CREDITO    NUMERIC(15,4),
  OBSERVACOES       VARCHAR(1000),
  DATA_CADASTRO     TIMESTAMP,
  CIDADE_ID         BIGINT,
  PRIMARY KEY (ID)
);
COMMIT;

CREATE TABLE FORNECEDOR (
  ID                DM_ID NOT NULL,
  EMPRESA_ID        DM_ID,
  RAZAO_SOCIAL      DM_NOME,
  NOME_FANTASIA     DM_NOME,
  CNPJ              VARCHAR(18),
  IE                VARCHAR(20),
  ENDERECO          VARCHAR(200),
  CIDADE            VARCHAR(100),
  UF                CHAR(2),
  CEP               VARCHAR(10),
  TELEFONE          VARCHAR(20),
  EMAIL             VARCHAR(150),
  CONTATO           VARCHAR(100),
  ATIVO             DM_STATUS,
  TIPO_PESSOA       CHAR(1) DEFAULT 'J',
  CPF_CNPJ          VARCHAR(20),
  NUMERO            VARCHAR(20),
  COMPLEMENTO       VARCHAR(100),
  BAIRRO            VARCHAR(100),
  CELULAR           VARCHAR(20),
  OBSERVACOES       VARCHAR(1000),
  DATA_CADASTRO     TIMESTAMP,
  CIDADE_ID         BIGINT,
  PRIMARY KEY (ID)
);
COMMIT;

SET TERM ^ ;
CREATE TRIGGER TRG_CLIENTE_BI FOR CLIENTE ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ID IS NULL OR NEW.ID = 0) THEN
    NEW.ID = GEN_ID(GEN_CLIENTE_ID, 1);
  IF (NEW.DATA_CADASTRO IS NULL) THEN
    NEW.DATA_CADASTRO = CURRENT_TIMESTAMP;
END^

CREATE TRIGGER TRG_FORNECEDOR_BI FOR FORNECEDOR ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ID IS NULL OR NEW.ID = 0) THEN
    NEW.ID = GEN_ID(GEN_FORNECEDOR_ID, 1);
  IF (NEW.DATA_CADASTRO IS NULL) THEN
    NEW.DATA_CADASTRO = CURRENT_TIMESTAMP;
END^
SET TERM ; ^
COMMIT;

CREATE INDEX IDX_CLIENTE_CIDADE ON CLIENTE (CIDADE_ID);
CREATE INDEX IDX_FORNECEDOR_CIDADE ON FORNECEDOR (CIDADE_ID);
COMMIT;

/* ------------------------------------------------------------
   2) Clientes de volta (IDs preservados)
   ------------------------------------------------------------ */

INSERT INTO CLIENTE (
  ID, EMPRESA_ID, NOME, NOME_FANTASIA, CPF_CNPJ, RG_IE,
  ENDERECO, NUMERO, COMPLEMENTO, BAIRRO, CIDADE, UF, CEP,
  TELEFONE, EMAIL, ATIVO, TIPO_PESSOA, CELULAR, DATA_NASCIMENTO,
  LIMITE_CREDITO, OBSERVACOES, DATA_CADASTRO, CIDADE_ID
)
SELECT
  ID, EMPRESA_ID, NOME, NOME_FANTASIA, CPF_CNPJ, RG_IE,
  ENDERECO, NUMERO, COMPLEMENTO, BAIRRO, CIDADE, UF, CEP,
  TELEFONE, EMAIL, ATIVO, TIPO_PESSOA, CELULAR, DATA_NASCIMENTO,
  LIMITE_CREDITO, OBSERVACOES, DATA_CADASTRO, CIDADE_ID
FROM PESSOA
WHERE TIPO = 'C';
COMMIT;

/* ------------------------------------------------------------
   3) Fornecedores de volta (mapa inverso)
   ------------------------------------------------------------ */

CREATE TABLE MIGRA_FORN_VOLTA_018 (
  ID_PESSOA BIGINT NOT NULL PRIMARY KEY,
  ID_ANTIGO BIGINT NOT NULL UNIQUE
);
COMMIT;

INSERT INTO MIGRA_FORN_VOLTA_018 (ID_PESSOA, ID_ANTIGO)
SELECT P.ID,
       COALESCE(
         (SELECT M.ID_ANTIGO FROM MIGRA_FORN_018 M WHERE M.ID_NOVO = P.ID),
         (SELECT COALESCE(MAX(ID_ANTIGO), 0) FROM MIGRA_FORN_018) +
         ROW_NUMBER() OVER (ORDER BY P.ID)
       )
FROM PESSOA P
WHERE P.TIPO = 'F';
COMMIT;

INSERT INTO FORNECEDOR (
  ID, EMPRESA_ID, RAZAO_SOCIAL, NOME_FANTASIA, CNPJ, IE,
  ENDERECO, CIDADE, UF, CEP, TELEFONE, EMAIL, CONTATO, ATIVO,
  TIPO_PESSOA, CPF_CNPJ, NUMERO, COMPLEMENTO, BAIRRO, CELULAR,
  OBSERVACOES, DATA_CADASTRO, CIDADE_ID
)
SELECT
  V.ID_ANTIGO, P.EMPRESA_ID, P.NOME, P.NOME_FANTASIA, M.CNPJ_ANTIGO,
  P.RG_IE, P.ENDERECO, P.CIDADE, P.UF, P.CEP, P.TELEFONE, P.EMAIL,
  P.CONTATO, P.ATIVO, P.TIPO_PESSOA, P.CPF_CNPJ, P.NUMERO,
  P.COMPLEMENTO, P.BAIRRO, P.CELULAR, P.OBSERVACOES,
  P.DATA_CADASTRO, P.CIDADE_ID
FROM PESSOA P
JOIN MIGRA_FORN_VOLTA_018 V ON V.ID_PESSOA = P.ID
LEFT JOIN MIGRA_FORN_018 M ON M.ID_NOVO = P.ID
WHERE P.TIPO = 'F';
COMMIT;

/* ------------------------------------------------------------
   4) Referencias de fornecedor de volta
   ------------------------------------------------------------ */

UPDATE CONTA_PAGAR SET FORNECEDOR_ID =
  (SELECT V.ID_ANTIGO FROM MIGRA_FORN_VOLTA_018 V
    WHERE V.ID_PESSOA = CONTA_PAGAR.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_VOLTA_018 V
               WHERE V.ID_PESSOA = CONTA_PAGAR.FORNECEDOR_ID);

UPDATE NOTA_ENTRADA SET FORNECEDOR_ID =
  (SELECT V.ID_ANTIGO FROM MIGRA_FORN_VOLTA_018 V
    WHERE V.ID_PESSOA = NOTA_ENTRADA.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_VOLTA_018 V
               WHERE V.ID_PESSOA = NOTA_ENTRADA.FORNECEDOR_ID);

UPDATE PEDIDO_COMPRA SET FORNECEDOR_ID =
  (SELECT V.ID_ANTIGO FROM MIGRA_FORN_VOLTA_018 V
    WHERE V.ID_PESSOA = PEDIDO_COMPRA.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_VOLTA_018 V
               WHERE V.ID_PESSOA = PEDIDO_COMPRA.FORNECEDOR_ID);

UPDATE PRODUTO SET FORNECEDOR_ID =
  (SELECT V.ID_ANTIGO FROM MIGRA_FORN_VOLTA_018 V
    WHERE V.ID_PESSOA = PRODUTO.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_VOLTA_018 V
               WHERE V.ID_PESSOA = PRODUTO.FORNECEDOR_ID);

UPDATE FINANCEIRO SET FORNECEDOR_ID =
  (SELECT V.ID_ANTIGO FROM MIGRA_FORN_VOLTA_018 V
    WHERE V.ID_PESSOA = FINANCEIRO.FORNECEDOR_ID)
WHERE EXISTS (SELECT 1 FROM MIGRA_FORN_VOLTA_018 V
               WHERE V.ID_PESSOA = FINANCEIRO.FORNECEDOR_ID);
COMMIT;

/* ------------------------------------------------------------
   5) Avancar os geradores antigos
   ------------------------------------------------------------ */

SET TERM ^ ;
EXECUTE BLOCK AS
  DECLARE VMAX BIGINT;
  DECLARE VNOW BIGINT;
BEGIN
  SELECT COALESCE(MAX(ID), 0) FROM CLIENTE INTO :VMAX;
  VNOW = GEN_ID(GEN_CLIENTE_ID, 0);
  WHILE (VNOW < VMAX) DO
    VNOW = GEN_ID(GEN_CLIENTE_ID, 1);
END^

EXECUTE BLOCK AS
  DECLARE VMAX BIGINT;
  DECLARE VNOW BIGINT;
BEGIN
  SELECT COALESCE(MAX(ID), 0) FROM FORNECEDOR INTO :VMAX;
  VNOW = GEN_ID(GEN_FORNECEDOR_ID, 0);
  WHILE (VNOW < VMAX) DO
    VNOW = GEN_ID(GEN_FORNECEDOR_ID, 1);
END^
SET TERM ; ^
COMMIT;

/* ------------------------------------------------------------
   6) Remover a estrutura unificada
   ------------------------------------------------------------ */

DROP TABLE PESSOA;
DROP GENERATOR GEN_PESSOA_ID;
COMMIT;

DROP TABLE MIGRA_FORN_VOLTA_018;
DROP TABLE MIGRA_FORN_018;
COMMIT;

/* ------------------------------------------------------------
   7) Validacoes
   ------------------------------------------------------------ */

SELECT 'CLIENTE' AS TABELA, COUNT(*) AS QTD FROM CLIENTE
UNION ALL
SELECT 'FORNECEDOR', COUNT(*) FROM FORNECEDOR;

SELECT 'CONTA_PAGAR' AS TABELA, COUNT(*) AS ORFAOS
FROM CONTA_PAGAR CP
WHERE CP.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM FORNECEDOR F WHERE F.ID = CP.FORNECEDOR_ID)
UNION ALL
SELECT 'NOTA_ENTRADA', COUNT(*)
FROM NOTA_ENTRADA N
WHERE N.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM FORNECEDOR F WHERE F.ID = N.FORNECEDOR_ID)
UNION ALL
SELECT 'PEDIDO_COMPRA', COUNT(*)
FROM PEDIDO_COMPRA PC
WHERE PC.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM FORNECEDOR F WHERE F.ID = PC.FORNECEDOR_ID)
UNION ALL
SELECT 'PRODUTO', COUNT(*)
FROM PRODUTO PR
WHERE PR.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM FORNECEDOR F WHERE F.ID = PR.FORNECEDOR_ID)
UNION ALL
SELECT 'FINANCEIRO_FORN', COUNT(*)
FROM FINANCEIRO F
WHERE F.FORNECEDOR_ID > 0
  AND NOT EXISTS (SELECT 1 FROM FORNECEDOR X WHERE X.ID = F.FORNECEDOR_ID);

SELECT ID, CNPJ, CPF_CNPJ FROM FORNECEDOR ORDER BY ID;

SELECT GEN_ID(GEN_CLIENTE_ID, 0) AS GER_CLIENTE,
       (SELECT MAX(ID) FROM CLIENTE) AS MAX_CLIENTE,
       GEN_ID(GEN_FORNECEDOR_ID, 0) AS GER_FORNECEDOR,
       (SELECT MAX(ID) FROM FORNECEDOR) AS MAX_FORNECEDOR
FROM RDB$DATABASE;

SELECT COUNT(*) AS PESSOA_EXISTE
FROM RDB$RELATIONS
WHERE TRIM(RDB$RELATION_NAME) = 'PESSOA';

